# --- attachment bodies ------------------------------------------------------
#
# Real files of each type, small and generated. A demo that ships .pdf files
# which are not PDFs is a demo with a hole in it exactly where a client would
# poke.


def make_pdf(title: str, lines: list[str]) -> bytes:
    """A genuine one-page PDF. Opens in any reader; no library needed."""
    text = "".join(
        f"BT /F1 11 Tf 56 {720 - 18 * i} Td ({_pdf_escape(line)}) Tj ET\n"
        for i, line in enumerate([title, "", *lines])
    )
    stream = text.encode("latin-1")
    objects = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] "
        b"/Resources << /Font << /F1 5 0 R >> >> /Contents 4 0 R >>",
        b"<< /Length %d >>\nstream\n" % len(stream) + stream + b"\nendstream",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    ]

    out = bytearray(b"%PDF-1.4\n")
    offsets = []
    for number, body in enumerate(objects, start=1):
        offsets.append(len(out))
        out += b"%d 0 obj\n" % number + body + b"\nendobj\n"
    xref_at = len(out)
    out += b"xref\n0 %d\n" % (len(objects) + 1)
    out += b"0000000000 65535 f \n"
    for offset in offsets:
        out += b"%010d 00000 n \n" % offset
    out += b"trailer\n<< /Size %d /Root 1 0 R >>\nstartxref\n%d\n%%%%EOF\n" % (
        len(objects) + 1,
        xref_at,
    )
    return bytes(out)


def _pdf_escape(text: str) -> str:
    return text.replace("\\", r"\\").replace("(", r"\(").replace(")", r"\)")


def make_png(width: int, height: int, colour: tuple[int, int, int]) -> bytes:
    """A genuine PNG of one flat colour, built with zlib and struct."""
    raw = b"".join(b"\x00" + bytes(colour) * width for _ in range(height))

    def chunk(kind: bytes, payload: bytes) -> bytes:
        return (
            struct.pack(">I", len(payload))
            + kind
            + payload
            + struct.pack(">I", zlib.crc32(kind + payload) & 0xFFFFFFFF)
        )

    return (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0))
        + chunk(b"IDAT", zlib.compress(raw, 9))
        + chunk(b"IEND", b"")
    )


def make_zip_document(entries: dict[str, str]) -> bytes:
    """What .xlsx and .docx are underneath: a zip with fixed timestamps."""
    import io
    import zipfile

    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
        for name, body in entries.items():
            info = zipfile.ZipInfo(name, date_time=(1980, 1, 1, 0, 0, 0))
            archive.writestr(info, body)
    return buffer.getvalue()


def make_csv(header: list[str], rows: list[list[str]]) -> bytes:
    lines = [",".join(header), *[",".join(row) for row in rows]]
    return ("\r\n".join(lines) + "\r\n").encode("utf-8")


# --- the mailbox ------------------------------------------------------------


@dataclass
class Part:
    filename: str | None
    maintype: str
    subtype: str
    content: bytes
    broken_charset: bool = False


@dataclass
class Draft:
    key: str
    sender_name: str
    sender_email: str
    subject: str
    date: str | None
    body: str
    parts: list[Part] = field(default_factory=list)
    note: str = ""
    """Why this message is in the fixture. Copied into the ground truth so a
    reader of the test data knows which ones are load-bearing."""


