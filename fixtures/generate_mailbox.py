def _types_for(filename: str) -> tuple[str, str]:
    if filename.endswith(".csv"):
        return "text", "csv"
    if filename.endswith(".docx"):
        return "application", "vnd.openxmlformats-officedocument.wordprocessingml.document"
    return "application", "octet-stream"  # pragma: no cover - only two kinds here


def parseable(value: str | None) -> bool:
    if value is None:
        return False
    try:
        parsedate_to_datetime(value)
    except (TypeError, ValueError):
        return False
    return True


def build(draft: Draft, position: int) -> EmailMessage:
    message = EmailMessage()
    message["From"] = f"{draft.sender_name} <{draft.sender_email}>"
    message["To"] = "office@rookery-demo.example"
    message["Subject"] = draft.subject
    # A date the stdlib cannot parse cannot be *written* by the stdlib either:
    # `email.policy.default` serialises it as an empty `Date:` header, which
    # would make the bad-date fixture indistinguishable from the no-date one
    # and quietly stop testing anything. It is spliced in as raw bytes below
    # instead, which is how a mail client that emits rubbish would produce it.
    if parseable(draft.date):
        message["Date"] = draft.date
    message["Message-ID"] = f"<fixture-{position:03d}@rookery-demo.example>"
    message.set_content(draft.body + "\n")

    for part in draft.parts:
        kwargs = {"maintype": part.maintype, "subtype": part.subtype}
        if part.filename is not None:
            kwargs["filename"] = part.filename
        message.add_attachment(part.content, **kwargs)

    if draft.parts:
        # add_attachment picks a random boundary, which would make every
        # regeneration a diff. Fixing it keeps `make fixtures` a no-op.
        message.set_boundary(f"=-fixture-{position:03d}-=")
    for part, built in zip(draft.parts, message.iter_attachments()):
        if part.broken_charset:
            built.set_param("charset", "x-unknown-9000")
    return message


def main() -> int:
    MAILBOX.mkdir(parents=True, exist_ok=True)
    for stale in MAILBOX.glob("*.eml"):
        stale.unlink()

    items = drafts()
    truth = {
        "generated_by": "fixtures/generate_mailbox.py",
        "seed": SEED,
        "messages": [],
    }

    for position, draft in enumerate(items, start=1):
        message = build(draft, position)
        name = f"{position:03d}-{draft.key}.eml"
        data = message.as_bytes(policy=email.policy.SMTP)
        if draft.date is not None and not parseable(draft.date):
            data = b"Date: " + draft.date.encode("ascii") + b"\r\n" + data
        (MAILBOX / name).write_bytes(data)
        truth["messages"].append(
            {
                "file": name,
                "sender_name": draft.sender_name,
                "sender_email": draft.sender_email,
                "subject": draft.subject,
                "date": draft.date,
                "note": draft.note,
                "attachments": [
                    {
                        "declared_filename": part.filename,
                        "content_type": f"{part.maintype}/{part.subtype}",
                        "size": len(part.content),
                        "sha256": hashlib.sha256(part.content).hexdigest(),
                        "decodable": not part.broken_charset,
                    }
                    for part in draft.parts
                ],
            }
        )

    GROUND_TRUTH.parent.mkdir(parents=True, exist_ok=True)
    GROUND_TRUTH.write_text(json.dumps(truth, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    attachments = sum(len(m["attachments"]) for m in truth["messages"])
    print(f"wrote {len(items)} messages ({attachments} attachments) to {MAILBOX}")
    print(f"wrote ground truth to {GROUND_TRUTH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
