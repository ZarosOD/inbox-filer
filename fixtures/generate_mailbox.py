#!/usr/bin/env python3
"""Write the synthetic mailbox and, from the same values, its ground truth.

Nothing here is real. The senders are all under `.example`, which is reserved
by RFC 2606 and can never be a live domain; the names, subjects, amounts and
attachment contents are invented; and the attachments are generated byte by
byte rather than copied from anywhere.

The point of generating the ground truth here rather than recording what the
tool produced is that `tests/expected.json` then describes the *mailbox*. A
test that asserts against it is asking "did the reader read this message
correctly", not "does the reader still agree with itself".

    python fixtures/generate_mailbox.py

Deterministic: same bytes every run, including the multipart boundaries and
the random-looking file contents, so regenerating the fixture is a no-op in
git unless something here actually changed.
"""

